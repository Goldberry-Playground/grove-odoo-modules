"""Consult models: plan approval constraint and C.8 training-capture snapshots
(GOL-3575, spec C.4 / C.8).

Covers:
  * a plan can move to ``approved`` only when every section is approved (C.4);
  * first fill of a section body captures ``draft_body``/``draft_source``/
    ``draft_inputs`` once and never overwrites them (C.8);
  * ``action_approve`` writes ``approved_body``/``approved_at``/``by`` (C.8);
  * editing an approved section's body returns it to ``edited`` and blocks plan
    approval (C.8 + C.4);
  * the snapshot fields refuse a direct write for every group (C.8);
  * ``create_skeleton_sections`` makes empty sections marked ``skeleton``.

DB test (TransactionCase): listed in tests/__init__.py AND the root conftest
collect_ignore_glob so the pure-Python pytest collector skips it (GOL-1936).
"""

from odoo.exceptions import AccessError, ValidationError
from odoo.tests import TransactionCase, tagged
from odoo.tools import mute_logger


@tagged("post_install", "-at_install")
class TestConsultModels(TransactionCase):
    def setUp(self):
        super().setUp()
        self.lead = self.env["crm.lead"].create({"name": "Consult Lead", "grove_consult_stage": "design"})
        self.module = self.env["grove.consult.module"].create({"key": "lifecycle", "name": "Lifecycle"})
        self.plan = self.env["grove.consult.plan"].create({"lead_id": self.lead.id})

    def _section(self, **vals):
        base = {"plan_id": self.plan.id, "key": "lifecycle", "title": "Lifecycle"}
        base.update(vals)
        return self.env["grove.consult.plan.section"].create(base)

    # ── C.4 plan approval constraint ─────────────────────────────────────────

    def test_plan_cannot_approve_with_an_unapproved_section(self):
        self._section(status="generated")
        with self.assertRaises(ValidationError):
            self.plan.write({"status": "approved"})

    def test_plan_approves_when_every_section_is_approved(self):
        section = self._section(body="Drafted body")
        section.action_approve()
        self.plan.write({"status": "approved"})
        self.assertEqual(self.plan.status, "approved")
        self.assertEqual(self.plan.approved_by, self.env.user)
        self.assertTrue(self.plan.approved_at)

    # ── C.8 draft capture ────────────────────────────────────────────────────

    def test_first_fill_captures_the_draft_once(self):
        section = self._section()
        self.assertFalse(section.draft_body)
        section.write({"body": "First draft"})
        self.assertEqual(section.draft_body, "First draft")
        self.assertEqual(section.draft_source, "skeleton")
        # A second fill must not overwrite the captured draft.
        section.write({"body": "A human rewrote this entirely"})
        self.assertEqual(section.draft_body, "First draft")
        self.assertEqual(section.body, "A human rewrote this entirely")

    def test_draft_source_and_inputs_come_from_context(self):
        section = self._section()
        section.with_context(
            consult_draft_source="template:lifecycle@abc123",
            consult_draft_inputs={"lead_id": self.lead.id, "module_ids": [self.module.id]},
        ).write({"body": "Generated by a template"})
        self.assertEqual(section.draft_source, "template:lifecycle@abc123")
        self.assertEqual(section.draft_inputs["lead_id"], self.lead.id)

    # ── C.8 approval snapshot ────────────────────────────────────────────────

    def test_approve_writes_the_approved_snapshot(self):
        section = self._section(body="Signed-off text")
        section.action_approve()
        self.assertEqual(section.status, "approved")
        self.assertEqual(section.approved_body, "Signed-off text")
        self.assertTrue(section.approved_at)
        self.assertEqual(section.by, self.env.user)

    def test_edit_after_approve_returns_to_edited_and_blocks_plan_approval(self):
        section = self._section(body="Approved text")
        section.action_approve()
        self.assertEqual(section.status, "approved")
        # Editing the body of an approved section demotes it to ``edited``.
        section.write({"body": "Changed after sign-off"})
        self.assertEqual(section.status, "edited")
        # The approved snapshot is preserved from the sign-off.
        self.assertEqual(section.approved_body, "Approved text")
        # And the plan can no longer be approved until it is re-approved.
        with self.assertRaises(ValidationError):
            self.plan.write({"status": "approved"})

    # ── C.8 read-only snapshot fields ────────────────────────────────────────

    def test_snapshot_fields_refuse_a_direct_write(self):
        section = self._section(body="Body")
        for field, value in (
            ("draft_body", "hand-edited draft"),
            ("draft_source", "faked"),
            ("draft_inputs", {"x": 1}),
            ("approved_body", "faked approval"),
            ("approved_at", "2026-11-12 00:00:00"),
        ):
            with self.subTest(field=field), self.assertRaises(AccessError):
                section.write({field: value})

    # ── skeleton creation ────────────────────────────────────────────────────

    def test_create_skeleton_sections_are_empty_and_marked_skeleton(self):
        sections = self.plan.create_skeleton_sections(module_ids=[self.module.id])
        self.assertEqual(len(sections), 1)
        self.assertFalse(sections.body)
        self.assertFalse(sections.draft_body)
        self.assertEqual(sections.draft_source, "skeleton")
        self.assertEqual(sections.status, "generated")
        self.assertEqual(sections.module_id, self.module)

    def test_module_and_practice_keys_are_unique(self):
        with self.assertRaises(Exception), mute_logger("odoo.sql_db"):
            self.env["grove.consult.module"].create({"key": "lifecycle", "name": "Dup"})
            self.env.flush_all()
